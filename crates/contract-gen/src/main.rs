fn python(v: &Value) -> String {
    match v {
        Value::Null => "None".into(),
        Value::Bool(b) => if *b { "True" } else { "False" }.into(),
        Value::String(s) => serde_json::to_string(s).unwrap(),
        Value::Number(n) => n.to_string(),
        Value::Array(a) => format!("[{}]", a.iter().map(python).collect::<Vec<_>>().join(", ")),
        Value::Object(o) => format!(
            "{{{}}}",
            o.iter()
                .map(|(k, v)| format!("{}: {}", serde_json::to_string(k).unwrap(), python(v)))
                .collect::<Vec<_>>()
                .join(", ")
        ),
    }
}
fn main() {
    let mode = std::env::args().nth(1).unwrap_or_default();
    if !["generate", "check"].contains(&mode.as_str()) {
        eprintln!("usage: steam-patch-contract-gen generate|check");
        std::process::exit(2);
    }
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../packages/contracts");
    let mut drift = false;
    for (path, expected) in artifacts() {
        let path = root.join(path);
        if mode == "generate" {
            std::fs::create_dir_all(path.parent().unwrap()).unwrap();
            std::fs::write(&path, expected).unwrap();
        } else if std::fs::read(&path).ok().as_deref() != Some(expected.as_slice()) {
            eprintln!(
                "contract drift: {}",
                path.strip_prefix(&root).unwrap().display()
            );
            drift = true;
        }
    }
    if drift {
        std::process::exit(1);
    }
    println!("v4 contracts {mode}: ok");
}
